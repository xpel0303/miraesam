def book_tier(book: str) -> str:
    if book in BOOK_TIER:
        return BOOK_TIER[book]
    b = book or ""
    if re.search(r"고등|고교|수능|모의고사|구문", b):
        return "g7"
    for pat, t in ((r"1학년|중1|Level 1|\b1\b", "g4"), (r"2학년|중2|Level 2|\b2\b", "g5"), (r"3학년|중3|Level 3|\b3\b", "g6"), (r"Starter|초등", "g3")):
        if re.search(pat, b):
            return t
    return "g5"


def target_tier(book: str, level: str) -> str:
    """교재 단계를 기본으로, 쉬운 단계 교재의 '상'은 한 칸 위, 어려운 단계 교재의 '하'는 한 칸 아래로."""
    t = TIERS.index(book_tier(book))
    if level == "상" and t <= 3:  # 초등심화·중등기초 교재의 어려운 문항
        t += 1
    elif level == "하" and t >= 5:  # 중등심화·고등 교재의 쉬운 문항
        t -= 1
    return TIERS[t]


